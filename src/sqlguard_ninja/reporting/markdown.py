"""Human-readable Markdown reports (also used for the GitHub Actions job summary)."""

from __future__ import annotations

from typing import Any

from sqlguard_ninja.benchmarking.compare import Comparison


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def _ms(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.2f}"


def _ci(m: dict[str, Any], key: str) -> str:
    interval = (m.get("confidence_95") or {}).get(key)
    return "" if not interval else f" [{interval[0] * 100:.1f}-{interval[1] * 100:.1f}]"


def _row(name: str, m: dict[str, Any]) -> str:
    f1 = m.get("f1")
    return (
        f"| {name} | {m['cases']} | {_pct(m['recall'])}{_ci(m, 'recall')} | "
        f"{_pct(m['precision'])}{_ci(m, 'precision')} | "
        f"{'n/a' if f1 is None else f'{f1:.3f}'} | "
        f"{_pct(m['false_positive_rate'])}{_ci(m, 'false_positive_rate')} | "
        f"{_pct(m['false_negative_rate'])} | "
        f"{_pct(m['exact_match_rate'])} | {m['fn']} | {m['fp']} |"
    )


_HEADER = (
    "| Slice | Cases | Recall [95% CI] | Precision [95% CI] | F1 | FPR [95% CI] | FNR | "
    "Exact match | FN | FP |\n"
    "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"
)


def _basis_line(o: dict[str, Any]) -> str:
    basis = o.get("flag_basis", {})
    return (
        f"Flagged cases by basis: policy rule {basis.get('policy', 'n/a')}, unsupported or "
        f"unparseable SQL {basis.get('unsupported', 'n/a')}. Throughput: "
        f"{o.get('throughput_per_s', 'n/a')} evaluations/s (sequential)."
    )


def benchmark_report(result: dict[str, Any], *, max_examples: int = 15) -> str:
    m = result["metrics"]
    b, a, env = result["benchmark"], result["adapter"], result["environment"]
    lat = m["overall"]["latency_ms"]
    lines = [
        f"# SQL security benchmark — `{a['name']}` {a['version']}",
        "",
        f"Benchmark **{b['name']} {b['version']}** (fingerprint `{b['fingerprint']}`), "
        f"{b['cases_evaluated']} evaluations. Python {env['python']}, sqlglot "
        f"{env.get('sqlglot')}, {env['platform']}.",
        "",
        "Positive class = cases that must not run unattended (expected deny or review). "
        "Intervals are 95% Wilson score intervals.",
        "",
        "**Internal** cases were written or generated by this project. **Independent** cases "
        "come from outside sources and are reported separately, never pooled.",
        "",
        "## Summary",
        "",
        _HEADER,
        _row("all cases", m["overall"]),
        _row("within declared capability", m["within_capability"]),
        "",
        f"Latency per evaluation (ms): p50 {_ms(lat['p50'])}, p95 {_ms(lat['p95'])}, "
        f"p99 {_ms(lat['p99'])}, max {_ms(lat['max'])}. Validator errors: "
        f"{m['overall']['errors']}.",
        "",
        "## By dataset tier",
        "",
        _HEADER,
        *(_row(k, v) for k, v in m.get("by_tier", {}).items()),
        "",
        _basis_line(m["overall"]),
        "",
        "## By category",
        "",
        _HEADER,
        *(_row(k, v) for k, v in m["by_category"].items()),
        "",
        "## By dialect",
        "",
        _HEADER,
        *(_row(k, v) for k, v in m["by_dialect"].items()),
        "",
        "## By provenance",
        "",
        _HEADER,
        *(_row(k, v) for k, v in m["by_provenance"].items()),
        "",
    ]
    by_id = {c["id"]: c for c in result["cases"]}
    for title, key in (
        ("False negatives (unsafe, allowed)", "false_negative_examples"),
        ("False positives (safe, blocked)", "false_positive_examples"),
    ):
        ids = m[key][:max_examples]
        lines += [f"## {title}", ""]
        if not ids:
            lines += ["None.", ""]
            continue
        lines += ["| Case | Category | Expected | Actual | Reasons |", "|---|---|---|---|---|"]
        for cid in ids:
            c = by_id[cid]
            reasons = ", ".join(c["reasons"][:3]) or "—"
            lines.append(
                f"| `{cid}` | {c['category']} | {c['expected']} | {c['actual']} | {reasons} |"
            )
        lines.append("")
    return "\n".join(lines)


def comparison_report(comp: Comparison, *, max_items: int = 20) -> str:
    status = "✅ PASSED" if comp.passed else "❌ FAILED"
    b, n = comp.baseline, comp.candidate
    bm, nm = b["metrics"]["overall"], n["metrics"]["overall"]
    lines = [
        f"# SQL safety regression check: {status}",
        "",
        f"Baseline `{b['adapter']['name']} {b['adapter']['version']}` "
        f"(benchmark `{b['benchmark']['fingerprint']}`) vs candidate "
        f"`{n['adapter']['name']} {n['adapter']['version']}` "
        f"(benchmark `{n['benchmark']['fingerprint']}`).",
        "",
        "| Metric | Baseline | Candidate |",
        "|---|---:|---:|",
        f"| Recall | {_pct(bm['recall'])} | {_pct(nm['recall'])} |",
        f"| Precision | {_pct(bm['precision'])} | {_pct(nm['precision'])} |",
        f"| False-positive rate | {_pct(bm['false_positive_rate'])} | "
        f"{_pct(nm['false_positive_rate'])} |",
        f"| p95 latency (ms) | {_ms(bm['latency_ms']['p95'])} | {_ms(nm['latency_ms']['p95'])} |",
        "",
    ]
    if comp.failures:
        lines += ["## Gate failures", "", *(f"- {f}" for f in comp.failures), ""]
    sections = [
        ("Security regressions (unsafe query now allowed)", comp.security_regressions),
        ("  of which privacy", comp.sensitive_regressions),
        ("  of which tenant isolation", comp.tenant_regressions),
        ("Newly blocked legitimate queries", comp.usability_regressions),
        ("New validator errors", comp.new_errors),
        ("New parse failures on legitimate queries", comp.new_parse_failures),
        ("Changed expected labels (need explicit approval)", comp.label_changes),
        ("Approved relabels (LABEL_CHANGES.yaml)", comp.approved_label_changes),
        ("Other decision changes", comp.decision_changes),
        ("Improvements", comp.improvements),
    ]
    for title, ids in sections:
        lines.append(f"- **{title.strip()}**: {len(ids)}")
        for cid in ids[:max_items]:
            lines.append(f"  - `{cid}`")
    if comp.p95_change_pct is not None:
        lines.append(f"- **p95 latency change**: {comp.p95_change_pct:+.1f}%")
    lines += [
        "",
        "Baselines are never updated automatically. To accept intentional changes, run "
        "`sqlninja benchmark baseline` locally and commit the result for review.",
    ]
    return "\n".join(lines)
